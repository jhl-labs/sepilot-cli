export function swarmSystemPromptExtension(sessionId: string | undefined): string | null {
  if (!sessionId?.startsWith('swarm_')) return null
  return PROMPT
}

export function buildSwarmSupervisorTaskPrompt(goal: string): string {
  return [
    'Swarm goal:',
    goal,
    '',
    'Operational contract:',
    '- Coordinate the active external CLI worker through swarm.drive for ordinary task work.',
    '- Treat "do not use ask mode" or "use interactive/agent/CLI mode" as an instruction to drive the worker and observe the result, not to answer from the supervisor alone.',
    '- Do not implement a manual swarm.send + swarm.wait_idle loop unless swarm.drive cannot express the raw interaction.',
    '- Keep one active worker at a time; use swarm.set_active only for explicit handoff bookkeeping.',
    '- On swarm.drive status=blocked or required_action, do not retry the same prompt. Inspect with swarm.recover action=inspect_worker_output when useful, then escalate to the human or hand off.',
    '- On swarm.drive status=max_turns, treat the worker result as INCOMPLETE; use returned nextPrompt when present, otherwise continue with a sharper prompt, inspect, or hand off instead of claiming completion.',
    '- On swarm.drive status=timeout, do not immediately resend the same prompt. Use returned recoveryHint when present and inspect with swarm.recover action=inspect_worker_output before resend/restart/handoff; if resending is justified, call swarm.recover action=resend_prompt with an explicit prompt.',
    '- On swarm.drive status=dead, treat the worker process as gone; use returned recoveryHint when present, run swarm.recover action=check_transport when available, then restart_worker once or hand off with the last known context. If check_transport reports blocked preflight, do not restart; report the configuration issue or escalate with the preflight summary.',
    '- On swarm.recover code=AGENT_BLOCKED, treat it like required_action and do not keep resending/restarting without resolving or handing off the human-required prompt.',
    '- On swarm.recover code=RECOVERY_REQUIRES_HUMAN, do not skip to a later recovery step unless the required manual/configuration action is resolved.',
    '- On swarm.recover action=inspect_protocol_logs, use the returned protocol context before deciding whether to restart or hand off.',
    '- On successful swarm.recover action=restart_worker, continue on the returned replacementHandle/activeHandle. Use nextDriveInput when present; otherwise use suggestedNextStep.',
    '- On swarm.recover code=RECOVERY_REPLACEMENT_UNHEALTHY, do not drive the replacement. Escalate or hand off with the startup failure summary.',
    '- Finish only after the goal is complete, a concrete blocker is reported, or the run must be handed off.',
  ].join('\n')
}
